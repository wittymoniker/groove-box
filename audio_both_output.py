"""audio_both_output.py — GROOVEBOX_R32_HDMI_PLUS_ANALOG_20261109

HDMI *and* the hardware (analog speakers / headphones) play at the same time.

Choosing HDMI used to re-route the one playback path, which left the analog output
silent and, when the HDMI PCM was not ready, left the user "device-fishing" to get sound
back.  This module writes an ALSA configuration that defines, from the cards actually
present:

    groovebox_speakers   dmix on the analog PCM             "Groovebox · Speakers (<card>)"
    groovebox_hdmi       dmix on the HDMI/DP PCM            "Groovebox · HDMI (<card>)"
    groovebox_both       multi → route → plug over both     "Groovebox · Both outputs (Speakers + HDMI)"

Every device carries a ``hint.description`` so ``aplay -L``, PortAudio/sounddevice and
mpv list them under those names.  ``preferred_output()`` returns ``groovebox_both``
whenever an HDMI PCM exists, else the speakers device — so selecting "HDMI" in the UI
never takes the analog path away.  dmix means several players (Groovebox, mpv, the
hardware volume helper) share each card without exclusive-open failures.

Linux-only by nature (ALSA).  On other platforms every function is a harmless no-op.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import time

BOTH = "groovebox_both"
SPK = "groovebox_speakers"
HDMI = "groovebox_hdmi"
LABELS = {
    BOTH: "Groovebox · Both outputs (Speakers + HDMI)",
    SPK: "Groovebox · Speakers",
    HDMI: "Groovebox · HDMI",
}
_CACHE = {"at": 0.0, "cards": None}
_TTL = 15.0


def _aplay_l(timeout=2.0):
    try:
        return subprocess.run(["aplay", "-l"], capture_output=True, text=True, timeout=timeout).stdout
    except Exception:
        return ""


def detect_cards(refresh=False):
    """[{'card': 0, 'id': 'PCH', 'name': 'HDA Intel PCH', 'device': 0, 'dev_name': 'ALC... Analog', 'kind': 'analog'|'hdmi'}]"""
    now = time.monotonic()
    if not refresh and _CACHE["cards"] is not None and now - _CACHE["at"] < _TTL:
        return list(_CACHE["cards"])
    out = []
    if sys.platform.startswith("linux"):
        pat = re.compile(r"^card (\d+): (\S+) \[(.*?)\], device (\d+): (.*?) \[(.*?)\]", re.M)
        for m in pat.finditer(_aplay_l()):
            card, cid, cname, dev, dname, dsub = m.groups()
            low = (dname + " " + dsub + " " + cname).lower()
            kind = "hdmi" if ("hdmi" in low or "displayport" in low or "dp " in low) else "analog"
            if "digital" in low and "hdmi" not in low and "iec958" in low:
                kind = "spdif"
            out.append({"card": int(card), "id": cid, "name": cname.strip(), "device": int(dev),
                        "dev_name": dname.strip(), "sub": dsub.strip(), "kind": kind})
    _CACHE.update(at=now, cards=out)
    return list(out)


def pick_outputs(cards=None):
    cards = detect_cards() if cards is None else cards
    analog = next((c for c in cards if c["kind"] == "analog"), None)
    hdmi = next((c for c in cards if c["kind"] == "hdmi"), None)
    return analog, hdmi


def device_label(name, cards=None):
    """Human label for any ALSA / PortAudio device string."""
    s = str(name or "")
    key = s.split("/", 1)[-1]
    if key in LABELS:
        analog, hdmi = pick_outputs(cards)
        if key == SPK and analog:
            return "%s (%s)" % (LABELS[SPK], analog["name"])
        if key == HDMI and hdmi:
            return "%s (%s)" % (LABELS[HDMI], hdmi["name"])
        return LABELS[key]
    m = re.match(r"(?:plug)?hw:(?:CARD=)?(\w+)(?:,(?:DEV=)?(\d+))?", key)
    if m:
        for c in detect_cards() if cards is None else cards:
            if str(c["card"]) == m.group(1) or c["id"] == m.group(1):
                if m.group(2) is None or int(m.group(2)) == c["device"]:
                    return "%s · %s (%s)" % ("HDMI" if c["kind"] == "hdmi" else "Speakers", c["name"], key)
    return s


def _dmix(name, card, dev, label, rate=48000):
    return f"""
pcm.{name}_raw {{
    type dmix
    ipc_key {4000 + card * 8 + dev}
    ipc_perm 0666
    slave {{ pcm "hw:{card},{dev}" rate {rate} channels 2 period_size 1024 buffer_size 8192 format S32_LE }}
}}
pcm.{name} {{
    type plug
    slave.pcm "{name}_raw"
    hint {{ show on description "{label}" }}
}}
"""


def build_asoundrc(cards=None, rate=48000):
    """The ALSA configuration text for the detected cards ('' when nothing to do)."""
    analog, hdmi = pick_outputs(cards)
    if analog is None and hdmi is None:
        return ""
    parts = ["# Generated by Groovebox (audio_both_output) — HDMI and speakers play together.",
             "# Regenerated whenever the card set changes; edits are overwritten."]
    if analog:
        parts.append(_dmix(SPK, analog["card"], analog["device"], "%s (%s)" % (LABELS[SPK], analog["name"]), rate))
    if hdmi:
        parts.append(_dmix(HDMI, hdmi["card"], hdmi["device"], "%s (%s)" % (LABELS[HDMI], hdmi["name"]), rate))
    if analog and hdmi:
        parts.append(f"""
pcm.{BOTH}_multi {{
    type multi
    slaves.a {{ pcm "{SPK}_raw" channels 2 }}
    slaves.b {{ pcm "{HDMI}_raw" channels 2 }}
    bindings.0 {{ slave a channel 0 }}
    bindings.1 {{ slave a channel 1 }}
    bindings.2 {{ slave b channel 0 }}
    bindings.3 {{ slave b channel 1 }}
}}
pcm.{BOTH}_route {{
    type route
    slave {{ pcm "{BOTH}_multi" channels 4 }}
    ttable.0.0 1
    ttable.1.1 1
    ttable.0.2 1
    ttable.1.3 1
}}
pcm.{BOTH} {{
    type plug
    slave.pcm "{BOTH}_route"
    hint {{ show on description "{LABELS[BOTH]}" }}
}}
""")
    else:
        only = SPK if analog else HDMI
        parts.append(f"""
pcm.{BOTH} {{
    type plug
    slave.pcm "{only}_raw"
    hint {{ show on description "{LABELS[BOTH]} — only one output present" }}
}}
""")
    parts.append(f"""
# Default device: both outputs, so any player that asks for "default" is heard everywhere.
pcm.!default {{
    type plug
    slave.pcm "{BOTH}_route" if 0
    slave.pcm "{BOTH}"
}}
""".replace('    slave.pcm "%s_route" if 0\n' % BOTH, ""))
    return "\n".join(parts)


def config_path(system=False):
    if system or os.environ.get("GROOVEBOX_USER_SESSION") == "1" and os.access("/etc", os.W_OK):
        return "/etc/asound.conf"
    return os.path.join(os.path.expanduser("~"), ".asoundrc")


def install(path=None, rate=48000, force=False):
    """Write the configuration (only when it changed). Returns (written, path, text)."""
    if not sys.platform.startswith("linux"):
        return False, "", ""
    text = build_asoundrc(rate=rate)
    if not text:
        return False, "", ""
    path = path or config_path()
    try:
        old = open(path, encoding="utf-8").read() if os.path.isfile(path) else ""
    except Exception:
        old = ""
    if old == text and not force:
        return False, path, text
    if old and "Generated by Groovebox" not in old and not force:
        # Someone's own configuration: append ours as an include-free block, never clobber.
        text = old.rstrip() + "\n\n" + text
    try:
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
        return True, path, text
    except Exception:
        return False, path, text


def available_devices():
    """Names from ``aplay -L`` that this module defined (after install)."""
    try:
        txt = subprocess.run(["aplay", "-L"], capture_output=True, text=True, timeout=2.0).stdout
    except Exception:
        return []
    return [ln.strip() for ln in txt.splitlines() if ln.strip() in (BOTH, SPK, HDMI)]


def preferred_output(prefix="alsa/"):
    """The device every player should use: both outputs when HDMI exists, else speakers."""
    if not sys.platform.startswith("linux"):
        return ""
    analog, hdmi = pick_outputs()
    if analog is None and hdmi is None:
        return ""
    names = set(available_devices())
    if not names:
        install()
        names = set(available_devices())
    if BOTH in names:
        return prefix + BOTH
    if SPK in names:
        return prefix + SPK
    if HDMI in names:
        return prefix + HDMI
    return ""


def choices():
    """[(device, label)] for a device combo: Both first, then each real output."""
    analog, hdmi = pick_outputs()
    out = []
    if analog or hdmi:
        out.append((BOTH, LABELS[BOTH]))
    if analog:
        out.append((SPK, "%s (%s)" % (LABELS[SPK], analog["name"])))
    if hdmi:
        out.append((HDMI, "%s (%s)" % (LABELS[HDMI], hdmi["name"])))
    return out


def ensure_background(callback=None):
    """Install from a worker thread (aplay calls never block the GUI)."""
    import threading

    def _run():
        try:
            res = install()
        except Exception as exc:
            res = (False, "", str(exc))
        if callback:
            try:
                callback(res)
            except Exception:
                pass

    th = threading.Thread(target=_run, name="groovebox-audio-both", daemon=True)
    th.start()
    return th


if __name__ == "__main__":
    w, p, t = install(force="--force" in sys.argv)
    print(("written to " if w else "unchanged at ") + (p or "(no ALSA cards)"))
    for d, l in choices():
        print("  %-22s %s" % (d, l))
