"""boot_switcher.py — GROOVEBOX_R32_BOOT_SWITCHER_20261113

Upper-level switcher for testing and installing fixes without a full ISO rebuild cycle:

  * pick a runtime root / overlay to prefer on next launch
  * copy a drop-in fix folder over the active app tree (with backup)
  * toggle Secure Boot preference flag for the next build_both run
  * set one-shot env (UI scale, mem soft/hard, skip launcher) for the next process
  * show what the current process is actually running (cwd, fingerprint)

Safe by default: never deletes projects, samples, or exports. Fix installs
copy into a timestamped backup first.
"""
from __future__ import annotations

import json
import os
import shutil
import time
from pathlib import Path
from typing import Optional

try:
    from PyQt6.QtCore import Qt
    from PyQt6.QtWidgets import (
        QWidget, QVBoxLayout, QHBoxLayout, QLabel, QPushButton, QFileDialog,
        QComboBox, QCheckBox, QMessageBox, QTextEdit, QSpinBox, QGroupBox,
        QFormLayout, QApplication,
    )
except Exception:
    QWidget = object  # type: ignore


def _app_root() -> Path:
    return Path(__file__).resolve().parent


def _state_path() -> Path:
    base = os.environ.get("GROOVEBOX_DATA_DIR") or os.path.join(
        os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config"), "groovebox")
    Path(base).mkdir(parents=True, exist_ok=True)
    return Path(base) / "boot_switcher.json"


def load_state() -> dict:
    try:
        return json.loads(_state_path().read_text(encoding="utf-8"))
    except Exception:
        return {}


def save_state(d: dict) -> None:
    p = _state_path()
    tmp = p.with_suffix(".tmp")
    tmp.write_text(json.dumps(d, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, p)


def current_report() -> str:
    lines = [f"app_root: {_app_root()}"]
    lines.append(f"cwd: {os.getcwd()}")
    try:
        import release_info as ri
        lines.append(ri.describe())
    except Exception as exc:
        lines.append(f"release_info: {exc}")
    try:
        import compat_settings as cs
        s = cs.load()
        lines.append(f"ui_scale={s.get('ui_scale')} effective={cs.effective_ui_scale(s)} window={s.get('window_scale')}")
        lines.append(f"QT_SCALE_FACTOR={os.environ.get('QT_SCALE_FACTOR', '(unset)')}")
    except Exception as exc:
        lines.append(f"scale: {exc}")
    st = load_state()
    if st:
        lines.append(f"switcher_state: {json.dumps(st, sort_keys=True)}")
    return "\n".join(lines)


def install_fix_tree(src: Path, dest: Optional[Path] = None) -> str:
    """Copy *.py / *.json / *.md from src into dest (default app root). Backup first."""
    src = Path(src)
    dest = Path(dest or _app_root())
    if not src.is_dir():
        return f"FAIL: not a directory: {src}"
    stamp = time.strftime("%Y%m%d-%H%M%S")
    backup = dest / f".fix-backup-{stamp}"
    backup.mkdir(parents=True, exist_ok=True)
    copied = 0
    for path in src.rglob("*"):
        if not path.is_file():
            continue
        if path.suffix.lower() not in {".py", ".json", ".md", ".txt", ".xml", ".sh", ".mgr"}:
            continue
        rel = path.relative_to(src)
        target = dest / rel
        if target.is_file():
            bdest = backup / rel
            bdest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target, bdest)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        copied += 1
    save_state({**load_state(), "last_fix_src": str(src), "last_fix_backup": str(backup), "last_fix_at": stamp})
    return f"OK: installed {copied} file(s) from {src} → {dest}\nbackup: {backup}"


def write_next_launch_env(ui_scale: Optional[int] = None, mem_soft: Optional[int] = None,
                          mem_hard: Optional[int] = None, secure_boot: Optional[bool] = None,
                          skip_launcher: bool = False) -> str:
    """Write a small env file the launcher can source: ~/.config/groovebox/next_launch.env"""
    base = _state_path().parent
    path = base / "next_launch.env"
    lines = ["# generated by boot_switcher — consumed once if the launcher supports it"]
    if ui_scale is not None:
        lines.append(f"export GROOVEBOX_BOOT_UI_SCALE={int(ui_scale)}")
    if mem_soft is not None:
        lines.append(f"export GROOVEBOX_MEM_SOFT_MB={int(mem_soft)}")
    if mem_hard is not None:
        lines.append(f"export GROOVEBOX_MEM_HARD_MB={int(mem_hard)}")
    if secure_boot is not None:
        lines.append(f"export GROOVEBOX_SECURE_BOOT={'1' if secure_boot else '0'}")
    if skip_launcher:
        lines.append("export GROOVEBOX_ALLOW_STARTUP_SKIP=1")
    __import__("safe_io").atomic_write_text(path, "\n".join(lines) + "\n", encoding="utf-8")
    save_state({**load_state(), "next_launch_env": str(path)})
    return f"wrote {path}\n" + "\n".join(lines)


class BootSwitcher(QWidget):
    def __init__(self, app=None, parent=None):
        super().__init__(parent)
        self.app = app
        self.setWindowTitle("Groovebox · Boot / Fix Switcher")
        self.resize(680, 520)
        try:
            import window_manager as wm
            wm.make_independent(self)
        except Exception:
            pass
        lay = QVBoxLayout(self)
        self.report = QTextEdit(); self.report.setReadOnly(True); self.report.setPlainText(current_report())
        lay.addWidget(QLabel("Current runtime"))
        lay.addWidget(self.report, 1)

        g = QGroupBox("Install a fix folder (copies into app root, keeps backup)")
        gl = QHBoxLayout(g)
        self.fix_path = QLabel("(none)")
        b_browse = QPushButton("Browse…")
        b_install = QPushButton("Install fixes")
        b_browse.clicked.connect(self._browse)
        b_install.clicked.connect(self._install)
        gl.addWidget(self.fix_path, 1); gl.addWidget(b_browse); gl.addWidget(b_install)
        lay.addWidget(g)
        self._src = None

        g2 = QGroupBox("Next launch knobs")
        form = QFormLayout(g2)
        self.ui_scale = QSpinBox(); self.ui_scale.setRange(0, 300); self.ui_scale.setSpecialValueText("unchanged"); self.ui_scale.setValue(0)
        self.mem_soft = QSpinBox(); self.mem_soft.setRange(0, 64000); self.mem_soft.setSuffix(" MB"); self.mem_soft.setSpecialValueText("unchanged")
        self.mem_hard = QSpinBox(); self.mem_hard.setRange(0, 64000); self.mem_hard.setSuffix(" MB"); self.mem_hard.setSpecialValueText("unchanged")
        self.sb = QComboBox(); self.sb.addItems(["unchanged", "Secure Boot ON", "Secure Boot OFF"])
        self.skip = QCheckBox("Allow skip startup launcher (dev)")
        form.addRow("UI scale override", self.ui_scale)
        form.addRow("MEM soft", self.mem_soft)
        form.addRow("MEM hard", self.mem_hard)
        form.addRow("ISO Secure Boot flag", self.sb)
        form.addRow(self.skip)
        b_write = QPushButton("Write next_launch.env")
        b_write.clicked.connect(self._write_env)
        form.addRow(b_write)
        lay.addWidget(g2)

        row = QHBoxLayout()
        b_ref = QPushButton("Refresh report")
        b_ref.clicked.connect(lambda: self.report.setPlainText(current_report()))
        b_console = QPushButton("Open console")
        b_console.clicked.connect(self._console)
        row.addWidget(b_ref); row.addWidget(b_console); row.addStretch(1)
        lay.addLayout(row)

    def _browse(self):
        path = QFileDialog.getExistingDirectory(self, "Fix folder (contains .py modules)")
        if path:
            self._src = Path(path)
            self.fix_path.setText(path)

    def _install(self):
        if not self._src:
            QMessageBox.information(self, "Fix install", "Choose a folder first.")
            return
        msg = install_fix_tree(self._src)
        self.report.setPlainText(msg + "\n\n" + current_report())
        QMessageBox.information(self, "Fix install", msg)

    def _write_env(self):
        ui = self.ui_scale.value() or None
        if ui == 0:
            ui = None
        soft = self.mem_soft.value() or None
        hard = self.mem_hard.value() or None
        sb = None
        if self.sb.currentIndex() == 1:
            sb = True
        elif self.sb.currentIndex() == 2:
            sb = False
        msg = write_next_launch_env(ui_scale=ui, mem_soft=soft, mem_hard=hard, secure_boot=sb,
                                   skip_launcher=self.skip.isChecked())
        self.report.setPlainText(msg + "\n\n" + current_report())

    def _console(self):
        try:
            import command_console
            command_console.open_window(self.app)
        except Exception as exc:
            QMessageBox.warning(self, "Console", str(exc))


def open_window(app=None):
    win = getattr(app, "_boot_switcher", None) if app is not None else None
    if win is None:
        win = BootSwitcher(app)
        if app is not None:
            try:
                app._boot_switcher = win
            except Exception:
                pass
    win.show(); win.raise_(); win.activateWindow()
    return win
